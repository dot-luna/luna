#!/usr/bin/env bash
# Install modular Zsh defaults and source them before personal startup settings.
# Extra arguments are ignored; optional mise completions may warn and skip.
set -euo pipefail

script_path=$(readlink -f -- "${BASH_SOURCE[0]}")
source "$(dirname -- "$script_path")/../../lib/common.sh"

setup_dir=$(luna_script_dir "${BASH_SOURCE[0]}")
repo_dir=$(dirname -- "$(dirname -- "$setup_dir")")
luna_resolve_config_dir
zsh_dir="$LUNA_CONFIG_DIR/zsh"
startup_dir=${ZDOTDIR:-"$HOME"}
if [[ "$startup_dir" != /* ]]; then
    luna_error 'ZDOTDIR must be an absolute path.'
    exit 1
fi
startup_file="$startup_dir/.zshrc"
static_files=(completion.zsh tools.zsh plugins.zsh zshrc)
generated_files=(generated/env.zsh generated/mise-completion.zsh)
retired_files=(
    paths.zsh development.zsh interactive.zsh mise.zsh zoxide.zsh fzf.zsh
    starship.zsh env.zsh mise-completion.zsh
    autogenerated/env.zsh autogenerated/mise-completion.zsh
)

# Check directory aliases before staging or replacing installed configuration.
if [[ -L "$zsh_dir" ]]; then
    luna_error "Zsh configuration destination must not be a symlink: $zsh_dir"
    exit 1
fi
resolved_zsh=$(realpath -m -- "$zsh_dir")
resolved_startup=$(realpath -m -- "$startup_file")
if [[ "$resolved_zsh" == "$repo_dir" || "$resolved_zsh" == "$repo_dir/"* || "$repo_dir" == "$resolved_zsh/"* \
    || "$resolved_startup" == "$resolved_zsh" || "$resolved_startup" == "$resolved_zsh/"* \
    || "$resolved_startup" == "$repo_dir" || "$resolved_startup" == "$repo_dir/"* ]]; then
    luna_error 'Zsh source, installed config, and personal .zshrc must be separate paths.'
    exit 1
fi
if [[ -e "$startup_file" && ! -f "$startup_file" ]]; then
    luna_error "Expected a regular Zsh startup file: $startup_file"
    exit 1
fi
for name in generated autogenerated; do
    if [[ -L "$zsh_dir/$name" || ( -e "$zsh_dir/$name" && ! -d "$zsh_dir/$name" ) ]]; then
        luna_error "Expected a generated config directory, not a file or symlink: $zsh_dir/$name"
        exit 1
    fi
done
for name in "${static_files[@]}" "${generated_files[@]}" "${retired_files[@]}"; do
    if [[ -d "$zsh_dir/$name" && ! -L "$zsh_dir/$name" ]]; then
        luna_error "Expected a configuration file, found a directory: $zsh_dir/$name"
        exit 1
    fi
done

luna_warn 'Back up files you want to keep; Zsh setup updates its files without backups.'
mkdir -p -- "$LUNA_CONFIG_DIR"
staging_dir=$(mktemp -d "$LUNA_CONFIG_DIR/.zsh-XXXXXX")
trap 'rm -rf -- "$staging_dir"' EXIT

for name in "${static_files[@]}"; do
    cp -- "$repo_dir/apps/zsh/$name" "$staging_dir/$name"
done
mkdir -- "$staging_dir/generated"
# Record this checkout, even when an inherited override names a different one.
/usr/bin/python3 "$setup_dir/zsh-config.py" env "$repo_dir" "$LUNA_CONFIG_DIR" > "$staging_dir/generated/env.zsh"

# Generate completion code once during setup. Failed generation must not replace
# a previously installed completion; activation stays in tools.zsh for runtime PATH.
if luna_available mise; then
    if ! mise --cd "$HOME" completion zsh > "$staging_dir/generated/mise-completion.zsh"; then
        rm -f -- "$staging_dir/generated/mise-completion.zsh"
        luna_warn 'Mise completion generation failed; keeping any installed completion.'
    fi
else
    luna_warn 'Mise is unavailable; skipping Zsh completion generation.'
fi

# Preserve the newest saved completion when optional regeneration cannot run.
# Stage it before retiring old paths, including targets of existing file symlinks.
if [[ ! -f "$staging_dir/generated/mise-completion.zsh" ]]; then
    for name in generated/mise-completion.zsh autogenerated/mise-completion.zsh mise-completion.zsh; do
        if [[ -f "$zsh_dir/$name" ]]; then
            cp -- "$zsh_dir/$name" "$staging_dir/generated/mise-completion.zsh"
            break
        fi
    done
fi

mkdir -p -- "$zsh_dir/generated"
# Install helpers before the entry point so every newly referenced file is ready.
for name in "${generated_files[@]}" "${static_files[@]}"; do
    if [[ -f "$staging_dir/$name" ]]; then
        mv -fT -- "$staging_dir/$name" "$zsh_dir/$name"
    fi
done
/usr/bin/python3 "$setup_dir/zsh-config.py" include "$startup_file" "$zsh_dir/zshrc"

# Remove only filenames owned by older Luna layouts, never unrelated user files.
for name in "${retired_files[@]}"; do
    rm -f -- "$zsh_dir/$name"
done
if [[ -d "$zsh_dir/autogenerated" ]]; then
    rmdir --ignore-fail-on-non-empty -- "$zsh_dir/autogenerated"
fi
luna_success "Configured Luna Zsh: $startup_file"
