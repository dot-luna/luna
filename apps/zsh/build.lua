return function(ctx)
    for _, name in ipairs({ "zshrc", "completion.zsh", "tools.zsh", "plugins.zsh" }) do
        ctx.read("config/" .. name)
    end

    -- Validate saved completion paths before invoking an optional external tool.
    for _, name in ipairs({ "generated", "autogenerated" }) do
        local path = ctx.quote(ctx.destination .. "/" .. name)
        assert(not os.execute("test -L " .. path .. " || { test -e " .. path .. " && test ! -d " .. path .. "; }"),
            "Expected a generated config directory, not a file or symlink: " .. name)
        for _, file in ipairs({ "env.zsh", "mise-completion.zsh" }) do
            path = ctx.quote(ctx.destination .. "/" .. name .. "/" .. file)
            assert(not os.execute("test -d " .. path .. " && test ! -L " .. path),
                "Expected a configuration file, found a directory: " .. name .. "/" .. file)
        end
    end

    ctx.render("env.zsh.in", "generated/env.zsh", {
        install_dir = ctx.quote(ctx.root),
        config_dir = ctx.quote(ctx.config_dir),
    })

    -- Cache completions during setup; mise activation stays in the running shell.
    if os.execute("command -v mise >/dev/null 2>&1") then
        local command = "mise --cd " .. ctx.quote(os.getenv("HOME")) .. " completion zsh"
        local process = assert(io.popen(command, "r"))
        local completion = process:read("*a")
        if process:close() then
            ctx.write("generated/mise-completion.zsh", completion)
            return
        end
        ctx.warn("Mise completion generation failed; keeping any installed completion.")
    else
        ctx.warn("Mise is unavailable; skipping Zsh completion generation.")
    end

    -- Migrate the newest complete copy before old Luna paths are retired.
    for _, name in ipairs({
        "generated/mise-completion.zsh",
        "autogenerated/mise-completion.zsh",
        "mise-completion.zsh",
    }) do
        local previous = io.open(ctx.destination .. "/" .. name, "rb")
        if previous then
            local completion = previous:read("*a")
            previous:close()
            assert(completion, "Cannot read saved mise completion")
            ctx.write("generated/mise-completion.zsh", completion)
            break
        end
    end
end
