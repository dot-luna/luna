#!/usr/bin/lua -E
-- Print generated/paths.lua for setup to stage beside the static Hyprland config.
-- Extra arguments are ignored; theme colors remain resolved when Hyprland loads.
local function generate()
    local quoted_path = "'" .. arg[0]:gsub("'", "'\\''") .. "'"
    local pipe = assert(io.popen("readlink -f -- " .. quoted_path, "r"))
    local path = pipe:read("*a")
    assert(pipe:close(), "Cannot locate the Hyprland configuration generator")
    local root = assert(path:gsub("\n$", ""):match("^(.*)/apps/hypr/scripts/[^/]+$"),
        "Hyprland configuration generator must remain inside the Luna checkout")

    -- Lua's quoted-string format preserves quotes, backslashes and line breaks
    -- without treating checkout names as executable configuration fragments.
    local output = string.format("-- Generated by Luna setup; keep the checkout in place.\nreturn {\n    install_dir = %q,\n}\n", root)
    assert(io.stdout:write(output))
    assert(io.stdout:flush())
end

local ok, message = pcall(generate)
if not ok then
    local detail = tostring(message):gsub("^.-:%d+: ", "")
    io.stderr:write("Cannot generate Hyprland configuration: " .. detail .. "\n")
    os.exit(1)
end
