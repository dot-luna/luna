"""Install per-user activation and transfer notification ownership to Luna."""
from contextlib import contextmanager
import fcntl
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time


UNIT = "luna-notifications.service"
ENVIRONMENT = (
    "WAYLAND_DISPLAY", "DISPLAY", "HYPRLAND_INSTANCE_SIGNATURE", "XDG_CURRENT_DESKTOP",
    "XDG_SESSION_TYPE", "XDG_SESSION_DESKTOP", "XDG_CONFIG_HOME", "XDG_DATA_HOME",
    "XDG_STATE_HOME", "LUNA_PATH", "PATH",
)


def run(arguments, check=True):
    result = subprocess.run(arguments, capture_output=True, text=True, timeout=35, check=False)
    if check and result.returncode:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or
                           f"{arguments[0]} exited with status {result.returncode}")
    return result


def systemctl(*arguments, check=True):
    return run(["systemctl", "--user", *arguments], check=check)


def reload_activation(check=True):
    # A newly created user service directory may not yet have a bus directory watch.
    return run(["busctl", "--user", "call", "org.freedesktop.DBus", "/org/freedesktop/DBus",
                "org.freedesktop.DBus", "ReloadConfig"], check=check)


def quoted(argument, systemd=False):
    # Neither activation format runs a shell. Systemd additionally expands % and $.
    if any(ord(character) < 32 or ord(character) == 127 for character in argument):
        raise ValueError("The Luna checkout path must not contain control characters")
    value = argument.replace("\\", "\\\\").replace('"', '\\"')
    if systemd:
        value = value.replace("%", "%%").replace("$", "$$")
    return '"' + value + '"'


def definitions(root):
    executable = str(root / "bin/luna")
    service = "\n".join((
        "# Generated by luna notifications setup.",
        "[Unit]", "Description=Luna notification service and desktop bar",
        "PartOf=graphical-session.target", "After=graphical-session.target", "",
        "[Service]", "Type=dbus", "BusName=org.freedesktop.Notifications",
        "ExecStart=" + quoted(executable, systemd=True) + " bar serve",
        "Restart=on-failure", "RestartSec=1", "TimeoutStartSec=20", "Slice=session.slice", "",
    ))
    activation = "\n".join((
        "# Generated by luna notifications setup.",
        "[D-BUS Service]", "Name=org.freedesktop.Notifications",
        "Exec=" + quoted(executable) + " bar serve", "SystemdService=" + UNIT, "",
    ))
    return service, activation


def write_file(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=".luna-notifications-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as file:
            file.write(content)
        os.chmod(name, 0o644)
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


@contextmanager
def setup_lock():
    runtime = Path(os.environ.get("XDG_RUNTIME_DIR", f"/tmp/luna-{os.getuid()}"))
    runtime.mkdir(mode=0o700, parents=True, exist_ok=True)
    # Do not unlink this inode: a second start may already be waiting on its lock.
    with (runtime / "luna-notifications-setup.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        yield


def ipc(root, method):
    return run(["qs", "ipc", "-p", str(root / "src/luna-bar"), "call", "bar", method], check=False)


def stop_standalone_bar(root):
    if ipc(root, "ping").returncode:
        return False
    if ipc(root, "stop").returncode:
        raise RuntimeError("Could not stop the existing Luna bar")
    for _ in range(30):
        if ipc(root, "ping").returncode:
            return True
        time.sleep(0.1)
    raise RuntimeError("The existing Luna bar did not stop")


def activate(root):
    if not os.environ.get("WAYLAND_DISPLAY"):
        raise RuntimeError("Start Luna notifications from a Wayland session")
    for executable in ("systemctl", "busctl", "qs"):
        if not shutil.which(executable):
            raise RuntimeError(f"{executable} is required for Luna notifications")
    if not (root / "bin/luna").is_file():
        raise RuntimeError("Cannot locate the Luna launcher")

    config_home = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
    data_home = Path(os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local/share")))
    service, activation = definitions(root)
    desired = {
        config_home / "systemd/user" / UNIT: service.encode(),
        data_home / "dbus-1/services/org.freedesktop.Notifications.service": activation.encode(),
    }

    with setup_lock():
        previous = {path: path.read_bytes() if path.exists() else None for path in desired}
        changed = any(previous[path] != content for path, content in desired.items())
        was_active = systemctl("is-active", "--quiet", UNIT, check=False).returncode == 0
        dunst_active = systemctl("is-active", "--quiet", "dunst.service", check=False).returncode == 0
        dunst_state = systemctl("show", "dunst.service", "--property=UnitFileState", "--value",
                                check=False).stdout.strip()
        dunst_masked = dunst_state in ("masked", "masked-runtime")
        stopped_bar = False
        changed_dunst = False
        try:
            for path, content in desired.items():
                if previous[path] != content:
                    write_file(path, content)
            if changed:
                systemctl("daemon-reload")
                reload_activation()

            # The systemd manager may predate the compositor; refresh only session variables.
            names = [name for name in ENVIRONMENT if name in os.environ]
            systemctl("import-environment", *names)
            if not was_active:
                stopped_bar = stop_standalone_bar(root)
            changed_dunst = not dunst_masked or dunst_active
            systemctl("mask", "--now", "dunst.service")
            systemctl("start", UNIT)
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError):
            # A failed takeover must not leave the prior daemon masked or activation broken.
            if not was_active:
                systemctl("stop", UNIT, check=False)
            for path, content in previous.items():
                if content is None:
                    path.unlink(missing_ok=True)
                else:
                    write_file(path, content)
            if changed:
                systemctl("daemon-reload", check=False)
                reload_activation(check=False)
            if changed_dunst:
                if not dunst_masked:
                    systemctl("unmask", "dunst.service", check=False)
                if dunst_active:
                    systemctl("start", "dunst.service", check=False)
            if stopped_bar:
                run([str(root / "bin/luna"), "bar", "start"], check=False)
            raise


if __name__ == "__main__":
    try:
        activate(Path(sys.argv[1]).resolve(strict=True))
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
