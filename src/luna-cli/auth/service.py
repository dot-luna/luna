"""Manage the session's polkit agent, validating Luna before transferring ownership."""
from contextlib import contextmanager
import fcntl
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time


UNIT = "luna-polkit.service"
KDE_UNIT = "plasma-polkit-agent.service"
ENVIRONMENT = (
    "WAYLAND_DISPLAY", "DISPLAY", "XDG_SESSION_ID", "XDG_CURRENT_DESKTOP",
    "XDG_SESSION_TYPE", "XDG_SESSION_DESKTOP", "HYPRLAND_INSTANCE_SIGNATURE",
    "XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME", "XDG_CACHE_HOME", "PATH",
)


def run(arguments, check=True, environment=None, timeout=15):
    result = subprocess.run(arguments, capture_output=True, text=True, timeout=timeout,
                            env=environment, check=False)
    if check and result.returncode:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or
                           f"{arguments[0]} exited with status {result.returncode}")
    return result


def systemctl(*arguments, check=True):
    return run(["systemctl", "--user", *arguments], check=check)


def quoted(argument):
    # ExecStart does not invoke a shell, but systemd expands % specifiers and $ variables.
    if any(ord(character) < 32 or ord(character) == 127 for character in argument):
        raise ValueError("The Luna checkout path must not contain control characters")
    return '"' + argument.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$") + '"'


def definition(root):
    return "\n".join((
        "# Generated by luna auth start.", "[Unit]",
        "Description=Luna desktop authentication agent", "PartOf=graphical-session.target",
        "After=graphical-session.target", "StartLimitIntervalSec=30", "StartLimitBurst=3", "",
        "[Service]", "Type=simple",
        "ExecStart=" + quoted(str(root / "bin/luna")) + " auth serve",
        "UnsetEnvironment=LUNA_INSTALL_DIR LUNA_POLKIT_VALIDATE LUNA_UI_THEME",
        "Restart=on-failure", "RestartSec=2", "TimeoutStopSec=5", "Slice=session.slice", "",
    )).encode()


def write_file(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=".luna-polkit-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as file:
            file.write(content)
        os.chmod(name, 0o644)
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


@contextmanager
def lifecycle_lock():
    runtime = Path(os.environ.get("XDG_RUNTIME_DIR", f"/tmp/luna-{os.getuid()}"))
    runtime.mkdir(mode=0o700, parents=True, exist_ok=True)
    # Keep the inode so simultaneous login hooks serialize on the same lock.
    with (runtime / "luna-polkit.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        yield


def shell_path(root):
    return (root / "src/luna-polkit/src/shell/shell.qml").resolve()


def ipc_status(root, timeout=3):
    result = run(["qs", "ipc", "-p", str(shell_path(root)), "call", "auth", "status"],
                 check=False, timeout=timeout)
    return result.stdout.strip() if result.returncode == 0 else None


def active(unit):
    return systemctl("is-active", "--quiet", unit, check=False).returncode == 0


def status(root):
    result = ipc_status(root)
    if result == "running":
        return "running"
    return "unavailable" if result is not None or active(UNIT) else "stopped"


def shell_instances(root):
    result = run(["qs", "list", "-a", "-j"], timeout=5).stdout.strip()
    if result in ("", "No running instances."):
        return []
    instances = json.loads(result)
    if not isinstance(instances, list):
        raise RuntimeError("Could not read Luna authentication processes")
    matches = []
    for instance in instances:
        if not isinstance(instance, dict) or not isinstance(instance.get("config_path"), str):
            raise RuntimeError("Could not read Quickshell process paths")
        if Path(instance["config_path"]).resolve() != shell_path(root):
            continue
        pid = instance.get("pid")
        if type(pid) is not int or pid <= 0:
            raise RuntimeError("Could not read the Luna authentication process ID")
        matches.append(pid)
    return matches


def stop_shell(root):
    instances = shell_instances(root)
    for pid in instances:
        result = run(["qs", "kill", "--pid", str(pid)], check=False, timeout=5)
        if result.returncode and pid in shell_instances(root):
            raise RuntimeError("Could not stop the existing Luna authentication agent")
    for _ in range(30):
        if not shell_instances(root):
            return bool(instances)
        time.sleep(0.1)
    raise RuntimeError("The existing Luna authentication agent did not stop")


def shell_environment(root):
    environment = dict(os.environ)
    imports = str(root / "src/qml")
    if environment.get("QML_IMPORT_PATH"):
        imports += ":" + environment["QML_IMPORT_PATH"]
    environment["QML_IMPORT_PATH"] = imports
    return environment


def validate(root):
    if not os.environ.get("WAYLAND_DISPLAY"):
        raise RuntimeError("Start Luna authentication from a Wayland login session")
    for executable in ("systemctl", "qs"):
        if not shutil.which(executable):
            raise RuntimeError(f"{executable} is required for Luna authentication")
    if not (root / "bin/luna").is_file() or not shell_path(root).is_file():
        raise RuntimeError("Cannot locate Luna's authentication shell")
    environment = shell_environment(root)
    environment["LUNA_POLKIT_VALIDATE"] = "1"
    result = run(["qs", "-p", str(shell_path(root))], environment=environment, timeout=10)
    if "Luna polkit validation passed" not in result.stdout + result.stderr:
        raise RuntimeError("Luna authentication validation failed; check the Quickshell polkit module")


def wait_registered(root):
    deadline = time.monotonic() + 12
    while time.monotonic() < deadline:
        try:
            if ipc_status(root, timeout=min(3, deadline - time.monotonic())) == "running":
                return
        except subprocess.TimeoutExpired:
            pass
        remaining = deadline - time.monotonic()
        if remaining > 0:
            time.sleep(min(0.1, remaining))
    raise RuntimeError("Luna could not register for authentication; check journalctl --user -u " + UNIT)


def activate(root, restart=False):
    with lifecycle_lock():
        # Import and component failures leave the current provider untouched.
        validate(root)
        config_home = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
        path = config_home / "systemd/user" / UNIT
        previous = path.read_bytes() if path.exists() else None
        desired = definition(root)
        changed = previous != desired
        was_active = active(UNIT)
        kde_active = active(KDE_UNIT)
        kde_state = systemctl("show", KDE_UNIT, "--property=UnitFileState", "--value", check=False).stdout.strip()
        kde_loaded = systemctl("show", KDE_UNIT, "--property=LoadState", "--value", check=False).stdout.strip()
        kde_masked = kde_state in ("masked", "masked-runtime")
        changed_kde = False
        stopped_standalone = False
        interrupted_luna = False
        attempted_start = False
        try:
            if changed:
                write_file(path, desired)
                systemctl("daemon-reload")
            names = [name for name in ENVIRONMENT if name in os.environ]
            systemctl("import-environment", *names)

            if was_active and not restart and not changed and ipc_status(root) == "running":
                return

            if was_active:
                interrupted_luna = True
                systemctl("stop", UNIT)
            stopped_standalone = bool(shell_instances(root)) and not was_active
            stop_shell(root)
            # A runtime mask prevents the previous login service from racing the new agent.
            # Keep existing masks intact, and only touch an installed KDE service.
            if kde_loaded and kde_loaded != "not-found":
                changed_kde = not kde_masked
                if not kde_masked:
                    systemctl("mask", "--runtime", "--now", KDE_UNIT)
                elif kde_active:
                    systemctl("stop", KDE_UNIT)
            systemctl("reset-failed", UNIT, check=False)
            attempted_start = True
            systemctl("start", UNIT)
            wait_registered(root)
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError):
            # Roll back only the ownership and unit file changed by this attempt.
            # One stalled recovery command must not prevent restoring the old provider.
            recovery_errors = []

            def recover(label, operation, *arguments, **keywords):
                try:
                    operation(*arguments, **keywords)
                except (OSError, ValueError, RuntimeError, subprocess.SubprocessError):
                    recovery_errors.append(label)

            if attempted_start:
                recover("stop Luna authentication", systemctl, "stop", UNIT)
            if changed:
                if previous is None:
                    recover("remove the new service file", path.unlink, missing_ok=True)
                else:
                    recover("restore the previous service file", write_file, path, previous)
                recover("reload user services", systemctl, "daemon-reload")
            if changed_kde:
                recover("unmask the previous agent", systemctl, "unmask", "--runtime", KDE_UNIT)
            if kde_active:
                recover("restart the previous agent", systemctl, "start", KDE_UNIT)
            if interrupted_luna:
                recover("restart Luna authentication", systemctl, "start", UNIT)
            elif stopped_standalone:
                recover("restart the standalone Luna agent", run,
                        ["qs", "-p", str(shell_path(root)), "--no-duplicate", "--daemonize"],
                        environment=shell_environment(root))
            if recovery_errors:
                print("Authentication recovery could not " + "; ".join(recovery_errors) +
                      ". Check systemctl --user status " + UNIT + " " + KDE_UNIT, file=sys.stderr)
            raise


def stop(root):
    with lifecycle_lock():
        loaded = systemctl("show", UNIT, "--property=LoadState", "--value", check=False).stdout.strip()
        if loaded and loaded != "not-found":
            systemctl("stop", UNIT)
        stop_shell(root)


def main(root, action):
    if action == "status":
        print(status(root))
    elif action == "stop":
        stop(root)
    elif action in ("start", "restart"):
        activate(root, restart=action == "restart")
    else:
        raise ValueError("Unknown authentication action: " + action)


if __name__ == "__main__":
    try:
        main(Path(sys.argv[1]).resolve(strict=True), sys.argv[2])
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
